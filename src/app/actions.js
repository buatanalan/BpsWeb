'use server';

import { getDbConnection } from '@/lib/db';
import fs from 'fs';
import path from 'path';

/**
 * Server Action to retrieve the test private key for easy local evaluation.
 * 
 * @returns {Promise<string>} Private Key PEM string or empty string if not available
 */
export async function getTestPrivateKey() {
  try {
    const keyPath = path.join(process.cwd(), 'keys', 'private.pem');
    if (fs.existsSync(keyPath)) {
      return fs.readFileSync(keyPath, 'utf8');
    }
  } catch (error) {
    console.error('Error loading test private key:', error);
  }
  return '';
}

