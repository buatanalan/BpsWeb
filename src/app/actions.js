/**
 * Server Action to search residents using HMAC-SHA256 hashes generated by the client.
 * Serves zero-knowledge Searchable Encryption. No keys are sent to the server.
 * 
 * @param {string} searchHash - HMAC-SHA256 hex string of the search word or query
 * @returns {Promise<{success: boolean, data?: Array, error?: string}>}
 */
export async function searchResidentsByHash(searchHash) {
  if (!searchHash || !/^[0-9a-fA-F]{64}$/.test(searchHash)) {
    return { success: true, data: [] }; // Return empty if invalid hash formatting
  }

  try {
    const db = await getDbConnection();
    const residents = await db.queryByHash(searchHash);

    // Strip indexes if they exist in returned data (safety)
    const cleanData = residents.map(({ nama_index, nik_index, ...rest }) => rest);
    return { success: true, data: cleanData };
  } catch (error) {
    console.error('Database query by hash failed:', error);
    return { success: false, error: 'Gagal melakukan query database terenkripsi.' };
  }
}
